# shellcheck shell=bash
# =========================================================================
# matugen パレット共通処理 (WSL / Mac の matugen-apply.sh から source する)
# =========================================================================
# matugen が出力した CSS パレット (palette.css テンプレートの生成物) から
# Material role を抽出し、派生色 (complement/triad/accent_pale) を計算して、
# OS に依存しないアプリ (WezTerm/nvim/yazi/starship/lazygit/cz/eza/tealdeer/
# btop/fzf) へ展開する。OS 固有の処理 (YASB/komorebi/AeroSpace 等) は
# 呼び出し側に残す。CSS 変数名と role の対応は docs/matugen-palette.md を参照。

MATUGEN_LIB="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MATUGEN_TPL="$MATUGEN_LIB/../templates"

# CSS 変数 --<name>: の値を #rrggbb で返す。
# --base 等は rgba(r, g, b, a) 形式 (半透明) の場合もあるため、hex に変換する
# (alpha は無視。以降の消費側は全てプレーンな hex を期待している)。
matugen_pal() {
    local css="$1" name="$2" line hex
    line="$(grep -m1 -- "--$name:" "$css" 2>/dev/null)" || return 0
    hex="$(echo "$line" | grep -oE '#[0-9a-fA-F]{6}' || true)"
    if [[ -n "$hex" ]]; then
        echo "$hex"
        return 0
    fi
    if [[ "$line" =~ rgba?\(([0-9]+)[,\ ]+([0-9]+)[,\ ]+([0-9]+) ]]; then
        printf '#%02x%02x%02x\n' "${BASH_REMATCH[1]}" "${BASH_REMATCH[2]}" "${BASH_REMATCH[3]}"
    fi
}

# matugen_build_palette <palette.css> <surface に使う CSS 変数名>
# 成功すると 0 を返し、以下のシェル変数を設定する (呼び出し側で参照するためグローバル):
#   accent tertiary secondary text muted surface on_accent error outline
#   complement triad accent_pale selection_bg
#   MATUGEN_LUA (共通 colors.lua を書いた一時ファイル。matugen_render_common が削除する)
# 必須キーが欠けていれば 1 を返す。
matugen_build_palette() {
    local css="$1" surface_role="$2" base_lua
    [[ -f "$css" ]] || return 1

    accent="$(matugen_pal "$css" highlight)"
    tertiary="$(matugen_pal "$css" accent-sub)"
    secondary="$(matugen_pal "$css" secondary)"
    text="$(matugen_pal "$css" text)"
    muted="$(matugen_pal "$css" subtext1)"
    surface="$(matugen_pal "$css" "$surface_role")"
    on_accent="$(matugen_pal "$css" base)"
    error="$(matugen_pal "$css" red)"
    outline="$(matugen_pal "$css" subtext0)"

    if [[ -z "$accent" || -z "$tertiary" || -z "$secondary" || -z "$text" \
          || -z "$muted" || -z "$surface" || -z "$on_accent" ]]; then
        return 1
    fi

    # complement/triad/accent_pale の色相回転・白ブレンド計算は NixOS と共通の
    # derive-colors.py。入力は colors.lua 形式なので一時ファイルを組み立てて渡す。
    base_lua="$(mktemp)"
    cat > "$base_lua" <<EOF
return {
  accent = "${accent}",
  tertiary = "${tertiary}",
  secondary = "${secondary}",
  text = "${text}",
  muted = "${muted}",
  surface = "${surface}",
  on_accent = "${on_accent}",
  error = "${error}",
}
EOF
    python3 "$MATUGEN_LIB/derive-colors.py" "$base_lua"
    complement="$(grep -m1 '^\s*complement\s*=' "$base_lua" | grep -oE '#[0-9a-fA-F]{6}' || true)"
    triad="$(grep -m1 '^\s*triad\s*=' "$base_lua" | grep -oE '#[0-9a-fA-F]{6}' || true)"
    accent_pale="$(grep -m1 '^\s*accent_pale\s*=' "$base_lua" | grep -oE '#[0-9a-fA-F]{6}' || true)"
    rm -f "$base_lua"

    [[ -n "$accent_pale" ]] || accent_pale="#c7dffe"
    [[ -n "$complement" ]] || complement="#f2d4ad"
    [[ -n "$triad" ]] || triad="#f2adcb"
    [[ -n "$error" ]] || error="#ffb4ab"
    [[ -n "$outline" ]] || outline="#c3c6cf"
    # starship の git_branch 表示と同じ色 (palettes.matugen の dark = 生の surface)
    # の方が好まれたため、明るく混ぜずに surface をそのまま使う。
    selection_bg="$surface"

    MATUGEN_LUA="$(mktemp)"
    cat > "$MATUGEN_LUA" <<LUA
-- Generated by matugen-apply — do not edit
return {
  accent = "${accent}",
  tertiary = "${tertiary}",
  secondary = "${secondary}",
  complement = "${complement}",
  triad = "${triad}",
  text = "${text}",
  muted = "${muted}",
  surface = "${surface}",
  on_accent = "${on_accent}",
  accent_pale = "${accent_pale}",
  error = "${error}",
  selection_bg = "${selection_bg}",
}
LUA
}

# matugen_render_common
# matugen_build_palette の結果を OS 共通のアプリへ展開する。
# 生成物の配置先は呼び出し側 (OS 固有処理) が参照できるよう固定パスにしている:
#   ~/.cache/matugen/colors.lua, ~/.cache/matugen/starship.toml 等
matugen_render_common() {
    local cache="$HOME/.cache/matugen" render="$MATUGEN_LIB/render-template.sh"
    mkdir -p "$cache/eza" "$cache/tealdeer" "$HOME/.config/wezterm" "$HOME/.config/btop/themes"

    # 共通 Lua パレット colors.lua (nvim / yazi / WezTerm が読む)
    command cp -f "$MATUGEN_LUA" "$HOME/.config/wezterm/matugen-colors.lua"
    command cp -f "$MATUGEN_LUA" "$cache/colors.lua"

    # @@プレースホルダ@@ テンプレートのレンダリング (NixOS と共通の render-template.sh)
    "$render" "$MATUGEN_TPL/starship.toml" "$cache/starship.toml" "$MATUGEN_LUA"
    "$render" "$MATUGEN_TPL/lazygit-theme.yml" "$cache/lazygit-theme.yml" "$MATUGEN_LUA"
    "$render" "$MATUGEN_TPL/cz.toml" "$cache/cz.toml" "$MATUGEN_LUA"
    if [[ -f "$HOME/.config/yazi/theme-template.toml" ]]; then
        "$render" "$HOME/.config/yazi/theme-template.toml" "$HOME/.config/yazi/theme.toml" "$MATUGEN_LUA"
    fi
    # eza (ls) の配色。ファイル名は theme.yml 固定でないと eza に認識されないため
    # 専用ディレクトリに置く (EZA_CONFIG_DIR で参照、modules/shell/zsh/functions.zsh 参照)
    "$render" "$MATUGEN_TPL/eza-theme.yml" "$cache/eza/theme.yml" "$MATUGEN_LUA"

    # tealdeer (tldr) は "#hex" を受け付けず rgb {r,g,b} 形式が必要なため専用スクリプトで生成
    python3 "$MATUGEN_LIB/tealdeer-config.py" "$MATUGEN_LUA" "$cache/tealdeer/config.toml"

    # btop のテーマ (color_theme = "matugen" 固定で、このファイルの中身だけを差し替える。
    # フォールバック版は home-manager の activation が同パスへ配置)
    "$render" "$MATUGEN_TPL/btop.theme" "$HOME/.config/btop/themes/matugen.theme" "$MATUGEN_LUA"

    # fzf (Ctrl+G の ghq ジャンプ等のハイライト配色)
    cat > "$cache/fzf-colors.sh.tmp" <<SH
# Generated by matugen-apply — do not edit
export FZF_DEFAULT_OPTS='--height 40% --layout=reverse --border --highlight-line --color=pointer:${accent},marker:${accent},prompt:${accent},info:${tertiary},hl:${tertiary},hl+:${tertiary},bg+:${selection_bg},spinner:${tertiary}'
SH
    mv "$cache/fzf-colors.sh.tmp" "$cache/fzf-colors.sh"

    rm -f "$MATUGEN_LUA"
}
